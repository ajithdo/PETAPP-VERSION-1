    required DateTime start,
    required int minutes,
    String mode = 'instant',
    required String status,
    required int price,
    int travelFee = 0,
    bool online = true,
    bool homeVisit = false,
    String? notes,
    List<DateTime> proposed = const [],
    DateTime? respondBy,
    DateTime? suggested,
    int refund = 0,
    bool reviewed = false,
    List<Map<String, dynamic>> updates = const [],
    List<({double lat, double lng})> walkRoute = const [],
    DateTime? createdAt,
    bool expense = false,
  }) {
    final a = areas[area]!;
    final commission = (price * 0.10).round();
    final total = price + travelFee;
    add('bookings', id, {
      'ownerId': owner,
      'ownerName': ownerName,
      'petId': petId,
      'petName': petName,
      'petSpecies': species,
      'kind': kind,
      'providerId': providerId,
      'providerName': providerName,
      'providerAddress': '${a.name}, ${a.city} ${a.pin}',
      'vetId': vetId,
      'vetName': vetName,
      'serviceId': serviceId,
      'serviceName': serviceName,
      'start': start,
      'end': start.add(Duration(minutes: minutes)),
      'mode': mode,
      'status': status,
      'proposedTimes': proposed,
      'respondBy': respondBy,
      'suggestedTime': suggested,
      'paymentOption': online ? 'online' : 'at_clinic',
      'paymentStatus': online && status != 'pending' && status != 'suggested' && status != 'expired' && status != 'declined'
          ? 'paid'
          : (online ? 'unpaid' : 'pay_at_visit'),
      'price': price,
      'travelFee': travelFee,
      'platformFee': 0,
      'discount': 0,
      'total': total,
      'commission': commission,
      'payout': total - commission,
      'refund': refund,
      'packageId': null,
      'homeVisit': homeVisit,
      'notes': notes,
      'photos': <String>[],
      'partnerUids': partnerUids,
      'reviewed': reviewed,
      'updates': updates,
      'walkRoute': [
        for (final p in walkRoute) {'lat': p.lat, 'lng': p.lng},
      ],
      'createdAt': createdAt ?? start.subtract(const Duration(days: 2)),
    });
    if (expense && owner.startsWith('u_') && !owner.startsWith('u_cust')) {
      add('expenses', 'exp_$id', {
        'ownerId': owner,
        'petId': petId,
        'category': switch (kind) {
          'clinic' => 'vet',
          'groomer' => 'grooming',
          'trainer' => 'training',
          'boarder' => 'boarding',
          _ => 'walking',
        },
        'amount': total - refund,
        'date': start,
        'note': '$serviceName · $providerName',
        'source': 'booking',
        'sourceId': id,
      });
    }
  }

