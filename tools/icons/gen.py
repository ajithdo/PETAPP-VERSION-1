"""Builds the app's icon set from the Phosphor fonts in the UI Design 6 kit.

  python3 tools/icons/gen.py            # fonts + lib/core/theme/ph.dart
  python3 tools/icons/gen.py --migrate  # also rewrite Icons.x -> Ph.y in lib/

Needs fonttools and brotli (pip install fonttools brotli). The icon names and
code points come from the kit's icons.css, so they always match the font.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from map import EXTRA, MAP  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KIT = os.path.join(ROOT, 'docs/design-proposals/2026-11-10-toran-redesign/source')
OUT = os.path.join(ROOT, 'lib/core/theme/ph.dart')
RENAME = {'export': 'exportUp'}


def dart_name(spec):
    name, _, fill = spec.partition(':')
    parts = name.split('-')
    ident = parts[0] + ''.join(p.capitalize() for p in parts[1:])
    ident = RENAME.get(ident, ident)
    return ident + ('Fill' if fill else '')


def main():
    css = open(os.path.join(KIT, 'icons.css')).read()
    codes = dict(re.findall(r'\.ph-([a-z0-9-]+):before\{content:"\\([0-9a-f]+)"\}', css))
    # Every icon comes in both cuts (`Ph.clock` and `Ph.clockFill`); unused
    # ones are dropped from release builds.
    names_used = {v.split(':')[0] for v in list(MAP.values()) + EXTRA}
    specs = sorted(names_used | {n + ':f' for n in names_used})
    missing = [s for s in specs if s.split(':')[0] not in codes]
    if missing:
        sys.exit(f'Not in the Phosphor font: {missing}')

    from fontTools.ttLib import TTFont
    for src, dst in (('Phosphor.woff2', 'Phosphor.ttf'), ('Phosphor-Fill.woff2', 'Phosphor-Fill.ttf')):
        font = TTFont(os.path.join(KIT, 'fonts', src))
        font.flavor = None
        font.save(os.path.join(ROOT, 'assets/fonts', dst))

    lines = [
        "import 'package:flutter/widgets.dart';",
        '',
        '/// The app\'s icons: Phosphor (MIT), the set UI Design 6 "Toran" is drawn',
        '/// with. Regular cut by default; names ending in `Fill` are the filled cut.',
        '///',
        '/// Generated by `python3 tools/icons/gen.py` from tools/icons/map.py. To',
        '/// add an icon, put its Phosphor name in EXTRA there and run the script.',
        'abstract final class Ph {',
        "  static const _regular = 'Phosphor';",
        "  static const _fill = 'PhosphorFill';",
        '',
    ]
    for spec in specs:
        name, _, fill = spec.partition(':')
        family = '_fill' if fill else '_regular'
        lines.append(f'  static const IconData {dart_name(spec)} = IconData(0x{codes[name]}, fontFamily: {family});')
    lines += ['}', '']
    open(OUT, 'w').write('\n'.join(lines))
    print(f'{len(specs)} icons -> {os.path.relpath(OUT, ROOT)}')

    if '--migrate' in sys.argv:
        migrate()


def migrate():
    changed = 0
    for base, _, files in os.walk(os.path.join(ROOT, 'lib')):
        for f in files:
            if not f.endswith('.dart') or f.endswith('.g.dart'):
                continue
            path = os.path.join(base, f)
            if os.path.abspath(path) == OUT:
                continue
            src = open(path).read()
            new = re.sub(r'\bIcons\.([a-zA-Z0-9_]+)', lambda m: 'Ph.' + dart_name(MAP[m.group(1)]), src)
            if new == src:
                continue
            rel = os.path.relpath(OUT, os.path.dirname(path)).replace(os.sep, '/')
            imp = f"import '{rel}';"
            if imp not in new:
                rows = new.split('\n')
                last = max(i for i, r in enumerate(rows) if r.startswith('import '))
                rows.insert(last + 1, imp)
                new = '\n'.join(rows)
            open(path, 'w').write(new)
            changed += 1
    print(f'{changed} files moved to Phosphor icons')


main()
